const mongoose = require('mongoose');
const { ObjectId } = mongoose.Schema.Types;
const { contactPattern } = require('../utils/validators');

// Medical history and lab reports are embedded: they are always read together with the patient
const historySchema = new mongoose.Schema({
  date: { type: Date, default: Date.now },
  diagnosis: { type: String, required: [true, 'Diagnosis is required'], trim: true },
  prescription: { type: String, trim: true, default: '' },
  notes: { type: String, trim: true, default: '' },
  doctor: { type: ObjectId, ref: 'Doctor' },
  addedBy: { type: ObjectId, ref: 'User' },
});

const labReportSchema = new mongoose.Schema({
  date: { type: Date, default: Date.now },
  testName: { type: String, required: [true, 'Test name is required'], trim: true },
  result: { type: String, required: [true, 'Result is required'], trim: true },
  notes: { type: String, trim: true, default: '' },
  addedBy: { type: ObjectId, ref: 'User' },
});

const patientSchema = new mongoose.Schema(
  {
    patientId: { type: String, required: true, unique: true, immutable: true }, // P001, P002, ... generated by the server
    name: { type: String, required: [true, 'Name is required'], trim: true },
    age: { type: Number, required: [true, 'Age is required'], min: [0, 'Age cannot be negative'], max: [120, 'Age must be 120 or less'] },
    gender: { type: String, required: [true, 'Gender is required'], enum: ['male', 'female', 'other'] },
    contact: { type: String, required: [true, 'Contact is required'], match: contactPattern },
    address: { type: String, trim: true, default: '' },
    bloodGroup: { type: String, enum: ['', 'A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'], default: '' },
    allergies: { type: String, trim: true, default: '' },
    condition: { type: String, trim: true, default: '' }, // current condition, used for search and filtering
    assignedDoctor: { type: ObjectId, ref: 'Doctor' },
    medicalHistory: [historySchema],
    labReports: [labReportSchema],
  },
  { timestamps: true }
);

patientSchema.index({ name: 1 });
patientSchema.index({ condition: 1 });
patientSchema.index({ assignedDoctor: 1 }); // "my patients" for doctors

module.exports = mongoose.model('Patient', patientSchema);
